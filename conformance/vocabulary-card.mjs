// Generates brain/KIPVocabulary.md, the compact model-facing list of the standard
// vocabulary, from the Schema packages. The packages are the source of truth: the
// card only abbreviates them, so it is regenerated, never edited.
//
//   node conformance/vocabulary-card.mjs            check the card against the packages
//   node conformance/vocabulary-card.mjs --write    regenerate it
import { readFile, writeFile } from 'node:fs/promises'
import { pathToFileURL } from 'node:url'

const base = new URL('../', import.meta.url)
export const CARD = 'brain/KIPVocabulary.md'
export const PACKAGES = ['profiles/cognitive-memory-2.0.0.schema.json',
  'profiles/general-domain-1.0.0.schema.json']

const local = ref => ref.slice(ref.lastIndexOf('/') + 1)
// A description's first sentence; a period inside a path or a section number does not end it.
const lead = text => (/^(.*?[.;:])(?=\s+[A-Z]|$)/s.exec(text.trim())?.[1] ?? text.trim()).replace(/[;:]$/, '.')
const names = values => values.map(value => '`' + value + '`').join(', ')

function endpoint(spec) {
  if (!spec) return 'any'
  if (spec.concept_types) return spec.concept_types.map(local).join(' | ')
  if (spec.literal_types) return spec.literal_types.join(' | ') + ' literal'
  if (spec.kinds) return spec.kinds.length === 5 ? 'any element' : spec.kinds.join(' | ')
  return 'any'
}

function fields(definitions) {
  const written = [], computed = []
  for (const [name, field] of Object.entries(definitions ?? {})) {
    const text = name + (field.required ? '*' : '') + (field.enum ? ' (' + field.enum.map(String).join(' | ') + ')' : '')
    ;(field.computed ? computed : written).push(text)
  }
  return [written.length ? written.join(', ') : '', computed.length ? 'computed: ' + computed.join(', ') : '']
    .filter(Boolean).join('; ')
}

function conceptType(name, def) {
  const attributes = fields(def.attributes?.fields)
  return `- \`${name}\`: ${lead(def.description)}` + (attributes ? ` Attributes: ${attributes}.` : '')
}

function predicate(name, def) {
  const slot = def.functional ? '; one value at a time' : def.functional_by === 'object_type'
    ? '; one value at a time per object type' : ''
  // A Predicate's whole description: it says how to write the claim, and there are few of them.
  return `- \`${name}\` (${endpoint(def.subject)} → ${endpoint(def.object)}${slot}): ${def.description.trim()}`
}

// A record Facet's package entry only points at the contract that defines it; its field
// list is that contract's value schema, which a writer reads in full or not at all.
const CONTRACT = /^\w+: normative contract in (.+?); value_schema is binding\.$/

function facet(name, def) {
  const contract = CONTRACT.exec(def.description.trim())
  if (contract) return `- \`${name}\` on ${endpoint(def.applicable_to)}: record defined in ${contract[1]}.`
  const list = fields(def.fields)
  return `- \`${name}\` on ${endpoint(def.applicable_to)}: ${lead(def.description)}` + (list ? ` Fields: ${list}.` : '')
}

function structuralField(name, def) {
  const marks = [def.ordered && 'ordered', def.computed && 'computed, read-only'].filter(Boolean)
  const source = def.source?.concept_types?.length > 4 ? 'memory product' : endpoint(def.source)
  return `- \`${name}\` (${source} → ${endpoint(def.target)}${marks.length ? '; ' + marks.join('; ') : ''}): ${lead(def.description)}`
}

const SECTIONS = [
  ['concept_types', 'Concept types', conceptType],
  ['predicates', 'Predicates', predicate],
  ['facets', 'Facets', facet],
  ['structural_fields', 'Structural fields', structuralField],
]

export function renderVocabularyCard(packages) {
  const out = [
    '# KIP vocabulary card',
    '',
    '<!-- Generated by conformance/vocabulary-card.mjs from the Schema packages. Do not edit. -->',
    '',
    'The standard vocabulary, one line per symbol. Write a name as a quoted string. A `*` marks a',
    'required attribute or field. This card abbreviates the packages; the live `DESCRIBE PRIMER`',
    'and `DESCRIBE TYPE | PREDICATE | FACET | STRUCTURAL FIELD` give the Space\'s own vocabulary,',
    'including its draft symbols, and the full definition of any symbol here.',
  ]
  for (const pkg of packages) {
    out.push('', `## \`${pkg.manifest.package_ref}\``)
    for (const [key, title, render] of SECTIONS) {
      const entries = Object.entries(pkg.definitions[key] ?? {})
      if (!entries.length) continue
      out.push('', `### ${title}`, '', ...entries.map(([name, def]) => render(name, def)))
    }
    const classes = pkg.definitions.registry_extensions?.activity_classes?.values
    if (classes?.length) out.push('', '### Activity classes', '', names(classes))
  }
  return out.join('\n') + '\n'
}

export async function loadPackages() {
  return Promise.all(PACKAGES.map(async file => JSON.parse(await readFile(new URL(file, base), 'utf8'))))
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const card = renderVocabularyCard(await loadPackages())
  const path = new URL(CARD, base)
  if (process.argv.includes('--write')) {
    await writeFile(path, card)
    console.log('Wrote', CARD)
  } else if (await readFile(path, 'utf8').catch(() => '') !== card) {
    console.error(`FAIL ${CARD} is out of date; run: node conformance/vocabulary-card.mjs --write`)
    process.exit(1)
  } else console.log('Verified', CARD)
}
